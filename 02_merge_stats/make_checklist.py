"""Generate TRAINING_CHECKLIST.md from results/*.json (initial version + notebook updater)."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
RESULTS = ROOT / "results"


def load(name, default=None):
    p = RESULTS / name
    if p.exists():
        try:
            return json.loads(p.read_text(encoding="utf-8"))
        except Exception:
            return default
    return default


